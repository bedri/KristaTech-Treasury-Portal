export function translate(locale: unknown, key: unknown): string {
  if (typeof key !== 'string' || !key) return ''
  if (key === '__proto__' || key === 'constructor' || key === 'prototype') {
    return key
  }
  const safeLocale = sanitizeLocale(locale, 'tr')
  const dict = translations[safeLocale] || translations.tr
  if (Object.prototype.hasOwnProperty.call(dict, key)) {
    return dict[key]!
  }
  if (Object.prototype.hasOwnProperty.call(translations.en, key)) {
    return translations.en[key]!
  }
  return key
}

const fallbackLocaleRef = ref<LocaleCode>('tr')

export function useI18n() {
  let localeState = fallbackLocaleRef
  try {
    // Use Nuxt SSR-safe useState when running inside Nuxt context
    if (typeof useState === 'function') {
      localeState = useState<LocaleCode>('krista_treasury_locale', () => 'tr')
    }
  } catch {
    localeState = fallbackLocaleRef
  }

  function setLocale(next: LocaleCode | string) {
    const clean = sanitizeLocale(next, 'tr')
    localeState.value = clean
    if (typeof window !== 'undefined') {
      try {
        window.localStorage.setItem('krista_treasury_locale', clean)
        document.documentElement.setAttribute('lang', clean)
      } catch {
        // Ignore storage errors in restricted contexts
      }
    }
  }

  function initLocaleFromStorage() {
    if (typeof window !== 'undefined') {
      try {
        const saved = window.localStorage.getItem('krista_treasury_locale')
        if (saved) {
          localeState.value = sanitizeLocale(saved, 'tr')
        }
        document.documentElement.setAttribute('lang', localeState.value)
      } catch {
        // Ignore storage errors
      }
    }
  }

  const currentLanguage = computed(
    () =>
      SUPPORTED_LANGUAGES.find((l) => l.code === localeState.value) || SUPPORTED_LANGUAGES[0]!
  )

  function t(key: string): string {
    return translate(localeState.value, key)
  }

  return {
    locale: localeState,
    languages: SUPPORTED_LANGUAGES,
    currentLanguage,
    setLocale,
    initLocaleFromStorage,
    t
  }
}
