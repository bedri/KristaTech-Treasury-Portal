export type LocaleCode = 'tr' | 'en' | 'de' | 'es' | 'fr' | 'ru' | 'zh' | 'ja' | 'ko' | 'pt'

export interface LanguageOption {
  code: LocaleCode
  name: string
  flag: string
}

